#!/usr/bin/env node
// Canonical server contract -> npm consumer; do not maintain a second schema.
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const raw=fs.readFileSync(path.join(root,'server/contracts/graph-query.v1.json'));
const hash=createHash('sha256').update(raw).digest('hex');
const manifest=JSON.parse(raw);
const output=`// Generated by Friday scripts/sync-graph-query-manifest.mjs. Do not edit.\nexport const GRAPH_QUERY_MANIFEST_HASH = '${hash}'\nexport const GRAPH_QUERY_MANIFEST = ${JSON.stringify(manifest,null,2)} as const\n`;
const target=path.join(root,'mcp/src/generated/graphQueryManifest.ts');
if(process.argv.includes('--check')) {
  if(!fs.existsSync(target)||fs.readFileSync(target,'utf8')!==output)throw new Error('npm graph_query contract is stale; run sync-graph-query-manifest.mjs');
} else {fs.mkdirSync(path.dirname(target),{recursive:true});fs.writeFileSync(target,output);}
console.log('npm graph_query manifest matches canonical contract');
