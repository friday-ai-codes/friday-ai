def is_generated_file(path: str, diff_text: str, line_count: int) -> bool:
    """生成文件判定：路径模式 或 diff 前 N 行含标记串 或 行数超阈值。

    命中只跳过"管线重活"（向量化 + 符号对齐），归档原文不跳（locked decision）。
    """
    for pattern in GENERATED_PATH_PATTERNS:
        if pattern.endswith("/"):
            if path.startswith(pattern) or f"/{pattern}" in f"/{path}":
                return True
        elif path.endswith(pattern):
            return True
    head_lines = diff_text.splitlines()[:_GENERATED_MARKER_PROBE_LINES]
    for line in head_lines:
        if any(marker in line for marker in GENERATED_CONTENT_MARKERS):
            return True
    return line_count > SINGLE_FILE_GENERATED_LINE_THRESHOLD


def _change_type(mr_file: MRDiffFile) -> str:
    if mr_file.new_file:
        return "added"
    if mr_file.deleted_file:
        return "deleted"
    if mr_file.renamed_file:
        return "renamed"
    return "modified"


def parse_diff_files(files: list[MRDiffFile]) -> list[FileDiff]:
    """把平台返回的 per-file diff 片段解析为文件级 ``FileDiff`` 列表。

    平台返回的 ``MRDiffFile.diff`` 是 hunk 级文本（不含 ``diff --git`` / ``---`` /
    ``+++`` 头，14-02 双客户端契约）——逐文件补头后**单独** ``unidiff.PatchSet``
    解析（RESEARCH 推荐的稳形态：单文件畸形不污染整批）。

    畸形防线（T-14-08，整批绝不 raise）：解析异常或"非空 diff 解析出零 hunk"
    （随机非 diff 文本被 unidiff 静默跳过的形态）均降级
    ``parse_failed=True`` + warning，统计/区间清零。
    """
    results: list[FileDiff] = []
    for mr_file in files:
        path = mr_file.new_path or mr_file.old_path
        old_path = mr_file.old_path or path
        change_type = _change_type(mr_file)
        diff_text = mr_file.diff or ""
        line_count = diff_text.count("\n")

        additions = 0
        deletions = 0
        hunk_ranges: list[tuple[int, int]] = []
        parse_failed = False
        try:
            source = "/dev/null" if mr_file.new_file else f"a/{old_path}"
            target = "/dev/null" if mr_file.deleted_file else f"b/{path}"
            patch = unidiff.PatchSet(f"--- {source}\n+++ {target}\n{diff_text}")
            hunk_count = 0
            for patched_file in patch:
                additions += patched_file.added
                deletions += patched_file.removed
                for hunk in patched_file:
                    hunk_count += 1
                    if hunk.target_length > 0:
                        hunk_ranges.append(
                            (hunk.target_start, hunk.target_start + hunk.target_length - 1)
                        )
            if diff_text.strip() and hunk_count == 0:
                # 非空 diff 解析出零 hunk：随机文本被 unidiff 当垃圾行跳过的形态
                raise unidiff.UnidiffParseError("non-empty diff yielded no hunks")
        except Exception as exc:
            logger.warning(
                "knowledge_diff_parse_failed",
                path=path,
                error=str(exc),
                error_type=type(exc).__name__,
            )
            parse_failed = True
            additions = 0
            deletions = 0
            hunk_ranges = []

        results.append(
            FileDiff(
                path=path,
                old_path=old_path,
                change_type=change_type,
                additions=additions,
                deletions=deletions,
                is_generated=is_generated_file(path, diff_text, line_count),
                parse_failed=parse_failed,
                hunk_ranges=hunk_ranges,
            )
        )
    return results


def compress_diff(text: str) -> bytes:
    """diff 原文 zlib 压缩（level 6 + utf-8，恒压缩无条件分支）。"""
    return zlib.compress(text.encode("utf-8"), 6)


def decompress_diff(blob: bytes) -> str:
    """``compress_diff`` 的逆操作（读取侧还原原文）。"""
    return zlib.decompress(bytes(blob)).decode("utf-8")


def _keep_lines_within_budget(text: str, allowed: int) -> str:
    """按行保留 utf-8 字节预算内的前缀（整行粒度，每行按 ``字节数 + 1`` 计换行）。"""
    kept: list[str] = []
    used = 0
    for line in text.splitlines():
        line_bytes = len(line.encode("utf-8")) + 1  # 含换行
        if used + line_bytes > allowed:
            break
        kept.append(line)
        used += line_bytes
    return "\n".join(kept)


def build_code_change_content(
    title: str,
    summary_lines: list[str],
    file_diffs: list[FileDiff],
    raw_by_path: dict[str, str],
    *,
    archive_id: str = "",
) -> str:
    """构造 code_change 实体的归一化 content（embedding 输入，受控大小）。

    结构：``{title}\\n\\n## 变更摘要\\n{...}\\n\\n## diff\\n{...}``。
    head（含文件清单）与 diff 区段共同受 ``MAX_CONTENT_BYTES`` 预算约束：
    文件清单超预算先截清单 + ``[摘要 truncated]`` 标注（WR-01：千文件长路径
    场景清单可达数百 KB，不截会击穿 version.content 受控大小语义）；diff 区段
    剔除生成文件与解析失败文件，超剩余预算按行截断（utf-8 安全）并以
    ``[diff truncated: 全文见归档 {archive_id}]`` 标注——全量原文永远在
    CodeChangeArchive（diff 原文绝不进 version.content 全量）。
    """
    summary = "\n".join(summary_lines)
    prefix = f"{title}\n\n## 变更摘要\n"
    tail = "\n\n## diff\n"
    diff_marker = f"\n[diff truncated: 全文见归档 {archive_id}]"
    # WR-01：head 也纳入总预算。预留 diff_marker 字节——summary 截断后剩余
    # diff 预算恒 >= len(diff_marker)，保证最终 content 严格 <= MAX_CONTENT_BYTES。
    summary_budget = MAX_CONTENT_BYTES - len((prefix + tail + diff_marker).encode("utf-8"))
    if len(summary.encode("utf-8")) > summary_budget:
        summary_marker = "\n[摘要 truncated: 文件清单超出预算]"
        allowed = max(summary_budget - len(summary_marker.encode("utf-8")), 0)
        summary = _keep_lines_within_budget(summary, allowed) + summary_marker
    head = prefix + summary + tail

    included = [
        raw_by_path[fd.path]
        for fd in file_diffs
        if not fd.is_generated and not fd.parse_failed and fd.path in raw_by_path
    ]
    diff_text = "\n".join(included)

    budget = MAX_CONTENT_BYTES - len(head.encode("utf-8"))
    if len(diff_text.encode("utf-8")) > budget:
        allowed = max(budget - len(diff_marker.encode("utf-8")), 0)
        diff_text = _keep_lines_within_budget(diff_text, allowed) + diff_marker
    return head + diff_text


