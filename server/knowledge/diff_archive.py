@dataclass(frozen=True)
class FileDiff:
    """单文件 diff 解析值对象（落 ``CodeChangeArchive.files`` JSON，asdict 序列化）。

    ``hunk_ranges`` 为新文件侧行区间列表 ``[(start, end), ...]``（符号对齐输入）；
    ``unresolved_symbols`` 为 ENH-01 懒解析跟踪载体（file+symbol+commit_sha 记录）。
    """

    path: str
    old_path: str
    change_type: str  # "added" | "modified" | "deleted" | "renamed"
    additions: int
    deletions: int
    is_generated: bool = False
    parse_failed: bool = False
    hunk_ranges: list[tuple[int, int]] = field(default_factory=list)
    unresolved_symbols: list[dict] = field(default_factory=list)


